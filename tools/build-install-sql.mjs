/**
 * Build the distributable MySQL 5.7 schema and reference-master SQL files.
 * This utility reads package assets only. It never opens a database connection.
 * Run from any working directory with Node.js 22/24 after `npm ci`.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { catalogDigest, emptySkuCatalog, TABLES } from '../server/db.mjs';
import { validateMasterCatalogs, validateDocument } from '../server/validation.mjs';
import { schemaSql } from '../server/relational.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sqlDirectory = resolve(root, 'database');
const catalogKeys = ['materials', 'shapes', 'tints'];
const migrationNames = ['001_initial.sql', '002_managed_catalogs.sql', '003_relational_documents.sql', '004_sku_power_ranges.sql'];
const sha256 = text => createHash('sha256').update(text).digest('hex');
const jsonExpression = value => 'CONVERT(0x' + Buffer.from(JSON.stringify(value), 'utf8').toString('hex') + ' USING utf8mb4)';

async function main() {
  if (process.argv.length !== 2) throw Error('Gunakan: node tools/build-install-sql.mjs');
  const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const catalogs = {};
  const sourceAssets = {};
  for (const key of catalogKeys) {
    const path = 'dist/assets/' + key + '.json';
    const bytes = await readFile(resolve(root, path));
    catalogs[key] = JSON.parse(bytes.toString('utf8'));
    sourceAssets[key] = {
      path, fileSha256: sha256(bytes), canonicalSha256: catalogDigest(catalogs[key]),
      compactJsonUtf8Bytes: Buffer.byteLength(JSON.stringify(catalogs[key]), 'utf8')
    };
  }
  validateMasterCatalogs(catalogs);
  const skuCatalog = emptySkuCatalog();
  validateDocument('skus', skuCatalog, catalogs);
  const { materials, shapes, tints } = catalogs;
  if (!materials.products.length || !materials.blanks.length || !materials.rules.length || !shapes.items.length || !tints.items.length) {
    throw Error('Aset master kosong atau tidak lengkap; SQL tidak dibuat.');
  }

  const migrations = [];
  await writeFile(resolve(sqlDirectory,'003_relational_documents.sql'),schemaSql(),'utf8');
  await writeFile(resolve(sqlDirectory,'004_sku_power_ranges.sql'),schemaSql({powerRangesOnly:true}),'utf8');
  for (const name of migrationNames) {
    const text = (await readFile(resolve(sqlDirectory, name), 'utf8')).trim();
    if (/^\s*(?:DROP|TRUNCATE|CREATE\s+DATABASE|CREATE\s+USER|GRANT)\b/im.test(text)) {
      throw Error('Migrasi berisi tindakan di luar cakupan paket instalasi: ' + name);
    }
    migrations.push('-- BEGIN ' + name + '\n' + text + '\n-- END ' + name);
  }

  const header = purpose => [
    '-- Leinz Lens Studio ' + pkg.version + ' — ' + purpose,
    '-- Target: MySQL 5.7.24; select the dedicated application database first.',
    '-- Generated by tools/build-install-sql.mjs from the complete packaged master assets.',
    '-- No DROP/TRUNCATE, database creation, MySQL accounts, or application passwords.',
    '-- This is reference installation data, not a backup of an existing installation.',
    '-- After importing, run npm run db:migrate to backfill and verify schema version 4.',
    'SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;', ''
  ].join('\n');
  const schemaBody = migrations.join('\n\n') + '\n';
  const seed = [
    '-- The schema migrations must be installed before this master-only section.',
    '-- Existing catalogs and the existing shared SKU document are preserved.',
    '-- Row lock matches server/db.mjs seed(), preventing partial concurrent catalog writes.',
    'START TRANSACTION;',
    'SELECT revision INTO @leinz_install_locked_revision',
    '  FROM leinz_catalog_revision WHERE id = 1 FOR UPDATE;',
    'SET @leinz_install_inserted_catalogs = 0;', ''
  ];
  for (const key of catalogKeys) {
    seed.push(
      '-- Complete ' + key + ' document; UTF-8 hex avoids quote/backslash SQL-mode differences.',
      'INSERT IGNORE INTO leinz_catalog_documents (document_key, document_json, source_sha256, updated_at)',
      "  VALUES ('" + key + "', " + jsonExpression(catalogs[key]) + ", '" + sourceAssets[key].canonicalSha256 + "', UTC_TIMESTAMP());",
      'SET @leinz_install_inserted_catalogs = @leinz_install_inserted_catalogs + ROW_COUNT();', ''
    );
  }
  seed.push(
    '-- No production SKU definition was supplied. Preserve an existing SKU document.',
    'INSERT IGNORE INTO leinz_workspace_documents (document_key, document_json, revision, updated_at)',
    "  VALUES ('skus', " + jsonExpression(skuCatalog) + ', 0, UTC_TIMESTAMP());',
    'SET @leinz_install_inserted_sku_documents = ROW_COUNT();',
    'UPDATE leinz_catalog_revision',
    '  SET revision = revision + 1, updated_at = UTC_TIMESTAMP()',
    '  WHERE id = 1 AND @leinz_install_inserted_catalogs > 0;',
    'COMMIT;', '',
    'SELECT @leinz_install_inserted_catalogs AS inserted_catalog_documents,',
    '       @leinz_install_inserted_sku_documents AS inserted_sku_documents;',
    'SET @leinz_install_locked_revision = NULL,',
    '    @leinz_install_inserted_catalogs = NULL,',
    '    @leinz_install_inserted_sku_documents = NULL;', ''
  );
  const seedBody = seed.join('\n');
  const outputs = {
    'leinz-schema.sql': header('schema only') + schemaBody,
    'leinz-master-data.sql': header('reference master data only') + seedBody,
    'leinz-schema-and-master-data.sql': header('schema and complete reference master data') + schemaBody + '\n' + seedBody
  };

  const productMap = new Map(materials.products.map(item => [item.id, item]));
  const blankMap = new Map(materials.blanks.map(item => [item.id, item]));
  const byProductField = field => [...new Set(materials.products.map(item => item[field]))].sort().map(value => ({
    [field]: value,
    products: materials.products.filter(item => item[field] === value).length,
    blanks: materials.blanks.filter(item => productMap.get(item.productId)[field] === value).length,
    powerRules: materials.rules.filter(item => productMap.get(blankMap.get(item.blankId).productId)[field] === value).length,
    diametersMm: [...new Set(materials.blanks.filter(item => productMap.get(item.productId)[field] === value).map(item => item.diameter))].sort((a, b) => a - b)
  }));
  const sourceRows = materials.rules.flatMap(item => item.sourceRows || []);
  const inventory = {
    schema: 'leinz-database-package-inventory/1.0',
    applicationVersion: pkg.version,
    targetDatabase: 'MySQL 5.7.24',
    dataScope: 'Complete packaged reference catalogs; not an export of an operational database or browser-local edits.',
    counts: {
      suppliers: new Set(materials.products.map(item => item.supplier)).size,
      products: materials.products.length, blanks: materials.blanks.length, powerRules: materials.rules.length,
      frameShapes: shapes.items.length, tinting: tints.items.length, skus: skuCatalog.skus.length
    },
    skuNote: 'No complete Master SKU export was supplied. The empty SKU catalog matches server seed. CREA2 shown in a screenshot is not a complete definition of its supplier/blank assignments and power ranges.',
    supplierBreakdown: byProductField('supplier'),
    indexBreakdown: byProductField('index'),
    simulatorIndices: [...new Set(materials.products.filter(item => item.activeForSimulator).map(item => item.index))].sort(),
    catalogOnlyIndices: [...new Set(materials.products.filter(item => !item.activeForSimulator).map(item => item.index))].sort(),
    shapes: shapes.items.map(item => ({ code: item.code, name: item.name, contourPointCount: item.points.length })),
    tintKinds: Object.fromEntries([...new Set(tints.items.map(item => item.kind))].sort().map(kind => [kind, tints.items.filter(item => item.kind === kind).length])),
    sourceRows: {
      declaredRows: materials.summary?.sourceRowCount ?? null,
      preservedRowReferences: sourceRows.length,
      uniqueReferencedRows: new Set(sourceRows).size,
      exactDuplicateExtraRows: materials.rules.reduce((total, item) => total + (item.exactDuplicateCount || 0), 0)
    },
    sourceAssets,
    tables: TABLES,
    schemaVersion: 4,
    requiresVerifiedBackfill: 'npm run db:migrate after SQL import; DDL alone records only versions 1 and 2',
    expectedFreshInstallation: {
      schemaMigrationRowsAfterSqlImport: 2, relationalDocumentRowsAfterBackfill: 4,
      schemaMigrationRows: 4, catalogDocumentRows: 3, catalogRevision: 1,
      skuDocumentRows: 1, skuItems: 0, applicationUsers: 0, sessions: 0, userDocuments: 0
    },
    sqlFiles: Object.fromEntries(Object.entries(outputs).map(([name, text]) => [name, { bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256(text) }]))
  };
  await mkdir(sqlDirectory, { recursive: true });
  for (const [name, text] of Object.entries(outputs)) await writeFile(resolve(sqlDirectory, name), text, 'utf8');
  await writeFile(resolve(sqlDirectory, 'master-data-inventory.json'), JSON.stringify(inventory, null, 2) + '\n', 'utf8');
  console.log(JSON.stringify({ ok: true, version: pkg.version, counts: inventory.counts, files: [...Object.keys(outputs), 'master-data-inventory.json'] }, null, 2));
}

main().catch(error => { console.error('Pembuatan SQL gagal: ' + error.message); process.exitCode = 1; });
